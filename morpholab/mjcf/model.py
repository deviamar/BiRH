"""``MjcfModel`` -- an MJCF tree plus everything needed to compile and address it.

Two responsibilities beyond holding XML:

1. **Compile with diagnostics.** MuJoCo's compiler errors point at a line in a string that
   nobody wrote by hand, so on failure this module re-emits the generated XML with line
   numbers and highlights the offending line.  Debugging a generated model is otherwise
   substantially worse than debugging a hand-written one.
2. **Name resolution.** Nothing outside a builder may string-format a MuJoCo name
   (``docs/00-REVIEW.md`` §3.7).  :class:`NameIndex` is the sanctioned way to get from a
   semantic role ("digit 1's distal pad") to a MuJoCo id.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import TYPE_CHECKING, Any, Iterable, Sequence

from ..core.logging import get_logger
from .element import Element, MjcfError

if TYPE_CHECKING:  # pragma: no cover - typing only; mujoco stays a lazy import
    import mujoco

log = get_logger(__name__)

__all__ = ["MjcfModel", "NameIndex", "CompileError"]


class CompileError(MjcfError):
    """Raised when MuJoCo rejects a generated model, with the XML context attached."""


@dataclass
class NameIndex:
    """Semantic role -> MuJoCo element name.

    Roles are grouped by kind (``body``, ``geom``, ``joint``, ``actuator``, ``site``,
    ``tendon``) so a lookup can be resolved to an integer id once a model is compiled and
    then reused for the life of the simulation.
    """

    bodies: dict[str, str] = field(default_factory=dict)
    geoms: dict[str, str] = field(default_factory=dict)
    joints: dict[str, str] = field(default_factory=dict)
    actuators: dict[str, str] = field(default_factory=dict)
    sites: dict[str, str] = field(default_factory=dict)
    tendons: dict[str, str] = field(default_factory=dict)
    groups: dict[str, list[str]] = field(default_factory=dict)
    """Named collections, e.g. ``{"pads": [...], "flexion_joints": [...]}``."""

    def merge(self, other: "NameIndex", *, prefix: str = "") -> "NameIndex":
        """Fold ``other`` into this index, optionally namespacing its role keys."""
        for kind in ("bodies", "geoms", "joints", "actuators", "sites", "tendons"):
            mine: dict[str, str] = getattr(self, kind)
            for role, name in getattr(other, kind).items():
                mine[f"{prefix}{role}"] = name
        for group, names in other.groups.items():
            self.groups.setdefault(f"{prefix}{group}", []).extend(names)
        return self

    def group(self, name: str) -> list[str]:
        """Names in a group, or an empty list -- absent groups are a normal condition
        (a hand with no thumb has no ``abduction_joints``)."""
        return list(self.groups.get(name, ()))

    def to_dict(self) -> dict[str, Any]:
        return {
            "bodies": dict(self.bodies), "geoms": dict(self.geoms), "joints": dict(self.joints),
            "actuators": dict(self.actuators), "sites": dict(self.sites),
            "tendons": dict(self.tendons), "groups": {k: list(v) for k, v in self.groups.items()},
        }


class MjcfModel:
    """A named MJCF tree that knows how to compile itself."""

    def __init__(
        self,
        root: Element,
        *,
        name: str = "model",
        index: NameIndex | None = None,
        assets: dict[str, bytes] | None = None,
        meta: dict[str, Any] | None = None,
    ) -> None:
        if root.tag != "mujoco":
            raise MjcfError(f"model root must be <mujoco>, got <{root.tag}>")
        self.root = root
        self.name = name
        self.index = index or NameIndex()
        self.assets = dict(assets or {})
        self.meta = dict(meta or {})

    # -- construction ---------------------------------------------------------------

    @classmethod
    def empty(cls, name: str = "model") -> "MjcfModel":
        return cls(Element("mujoco", model=name), name=name)

    def merge(self, other: "MjcfModel", *, prefix: str = "") -> "MjcfModel":
        """Merge another model's tree, assets and name index into this one."""
        self.root.merge(other.root)
        self.assets.update(other.assets)
        self.index.merge(other.index, prefix=prefix)
        self.meta.setdefault("merged", []).append(other.name)
        return self

    def section(self, tag: str) -> Element:
        return self.root.section(tag)

    @property
    def worldbody(self) -> Element:
        return self.root.section("worldbody")

    # -- serialization --------------------------------------------------------------

    def to_xml(self, *, header: str | None = None) -> str:
        return self.root.to_xml(header=header or f"generated by morpholab: {self.name}")

    def save(self, path: str | Path) -> Path:
        """Write the XML (and any in-memory assets) to disk, for inspection or archiving."""
        p = Path(path)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(self.to_xml(), encoding="utf-8")
        for asset_name, blob in self.assets.items():
            (p.parent / asset_name).write_bytes(blob)
        return p

    # -- compilation ----------------------------------------------------------------

    def validate(self) -> list[str]:
        """Structural problems found without invoking the compiler."""
        return self.root.validate()

    def compile(self, *, strict: bool = True) -> "mujoco.MjModel":
        """Compile to a ``mujoco.MjModel``.

        Parameters
        ----------
        strict:
            Raise on structural problems found by :meth:`validate` before compiling.
            A 10,000-job sweep must fail on a malformed model at build time, not on job
            9,999 (``docs/01-ARCHITECTURE.md`` §1.7).
        """
        import mujoco  # lazy: analysis-only contexts need no simulator

        if strict:
            problems = self.validate()
            if problems:
                shown = "\n  - ".join(problems[:10])
                more = "" if len(problems) <= 10 else f"\n  ... and {len(problems) - 10} more"
                raise CompileError(f"model {self.name!r} failed validation:\n  - {shown}{more}")

        xml = self.to_xml()
        try:
            if self.assets:
                return mujoco.MjModel.from_xml_string(xml, self.assets)
            return mujoco.MjModel.from_xml_string(xml)
        except (ValueError, RuntimeError) as exc:
            raise CompileError(self._explain(str(exc), xml)) from exc

    def compile_data(self) -> tuple["mujoco.MjModel", "mujoco.MjData"]:
        """Compile and allocate simulation state in one call."""
        import mujoco

        model = self.compile()
        return model, mujoco.MjData(model)

    def _explain(self, error: str, xml: str) -> str:
        """Attach numbered XML context to a compiler error."""
        lines = xml.splitlines()
        match = re.search(r"[Ll]ine[ :]+(\d+)", error)
        parts = [f"MuJoCo rejected generated model {self.name!r}:", f"  {error.strip()}"]
        if match:
            n = int(match.group(1))
            lo, hi = max(0, n - 6), min(len(lines), n + 5)
            parts.append("")
            parts += [
                f"  {'>>' if i + 1 == n else '  '} {i + 1:5d} | {lines[i]}" for i in range(lo, hi)
            ]
        else:
            parts.append(f"  ({len(lines)} lines; save with model.save(path) to inspect)")
        return "\n".join(parts)

    # -- introspection --------------------------------------------------------------

    def summary(self) -> dict[str, int]:
        """Element counts, cheap enough to log for every generated model."""
        counts: dict[str, int] = {}
        for node in self.root.walk():
            counts[node.tag] = counts.get(node.tag, 0) + 1
        return {
            "bodies": counts.get("body", 0),
            "geoms": counts.get("geom", 0),
            "joints": counts.get("joint", 0),
            "sites": counts.get("site", 0),
            "tendons": counts.get("fixed", 0) + counts.get("spatial", 0),
            "actuators": sum(counts.get(t, 0) for t in ("position", "motor", "general", "velocity")),
            "equality": counts.get("weld", 0) + counts.get("connect", 0),
        }

    def __repr__(self) -> str:
        s = self.summary()
        return (
            f"MjcfModel({self.name!r}, bodies={s['bodies']}, joints={s['joints']}, "
            f"actuators={s['actuators']})"
        )


def resolve_ids(model: "mujoco.MjModel", names: Iterable[str], kind: str) -> list[int]:
    """Resolve MuJoCo names to integer ids, raising a useful error on the first miss.

    ``kind`` is one of ``body``, ``geom``, ``joint``, ``actuator``, ``site``, ``tendon``.
    """
    import mujoco

    objtype = {
        "body": mujoco.mjtObj.mjOBJ_BODY,
        "geom": mujoco.mjtObj.mjOBJ_GEOM,
        "joint": mujoco.mjtObj.mjOBJ_JOINT,
        "actuator": mujoco.mjtObj.mjOBJ_ACTUATOR,
        "site": mujoco.mjtObj.mjOBJ_SITE,
        "tendon": mujoco.mjtObj.mjOBJ_TENDON,
    }[kind]

    out: list[int] = []
    for name in names:
        idx = mujoco.mj_name2id(model, objtype, name)
        if idx < 0:
            raise MjcfError(f"no {kind} named {name!r} in the compiled model")
        out.append(int(idx))
    return out


def joint_qpos_addresses(model: "mujoco.MjModel", joint_ids: Sequence[int]) -> list[int]:
    """``qpos`` addresses for hinge/slide joints (one address each)."""
    return [int(model.jnt_qposadr[j]) for j in joint_ids]


def joint_dof_addresses(model: "mujoco.MjModel", joint_ids: Sequence[int]) -> list[int]:
    """``qvel``/``qfrc`` addresses for hinge/slide joints."""
    return [int(model.jnt_dofadr[j]) for j in joint_ids]
